import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { EventEmitter } from 'node:events';
import { PassThrough } from 'node:stream';
import { test, after } from 'node:test';
const home = fs.mkdtempSync(path.join(process.env.TMPDIR || os.tmpdir(),'claude-history-'));
process.env.HOME=home; process.env.WORKSPACE_ROOT=home; process.env.ALLOWED_ROOT=home;
fs.mkdirSync(path.join(home,'.ssh'));
const { ClaudeService } = await import('../apps/api/src/services/claudeService.js');
const timers: ReturnType<typeof setTimeout>[]=[];
const originalTimeout=globalThis.setTimeout;
globalThis.setTimeout=((fn: any,delay: number,...args: any[])=>{const t=originalTimeout(fn,delay,...args);if(delay===600000)timers.push(t);return t;}) as typeof setTimeout;
after(()=>{for(const t of timers)clearTimeout(t);globalThis.setTimeout=originalTimeout;fs.rmSync(home,{recursive:true,force:true});});
test('background run through public session snapshot persists CLI identity, tokens and final history',async()=>{
 const service=new ClaudeService();
 const created=service.createSession('server-local','','Fixture',home,'Default');
 const child=Object.assign(new EventEmitter(),{stdout:new PassThrough(),stderr:new PassThrough(),kill(){}});
 (service as any).spawnLocalClaude=()=>child;
 service.addMessage(created.id,{id:'u1',sender:'user',text:'fixture',time:'00:00'});
 const snapshot=service.getSession(created.id)!;
 const task=service.startBackgroundPrompt(snapshot,'fixture');
 await new Promise(resolve=>setImmediate(resolve));
 const send=(frame:any)=>child.stdout.write(JSON.stringify(frame)+'\n');
 send({type:'system',subtype:'init',session_id:'native-history-id'});
 send({type:'assistant',message:{id:'native-message',content:[{type:'text',text:'Canonical persisted answer'}],usage:{input_tokens:12000,output_tokens:200,cache_read_input_tokens:3000}}});
 send({type:'result',subtype:'success',result:'Canonical persisted answer'});
 child.emit('close',0,null);await task.promise;
 const canonical=service.getSession(created.id)!;
 assert.equal(canonical.cliSessionId,'native-history-id','native resume id must belong to canonical session, not detached shallow snapshot');
 assert.equal(canonical.contextTokens,'15.2k');
 assert.equal(canonical.messages.at(-1)?.text,'Canonical persisted answer');
 assert.equal(canonical.isRunning,false);
 const restored=new ClaudeService().getSession(created.id)!;
 assert.equal(restored.cliSessionId,'native-history-id');
 assert.equal(restored.contextTokens,canonical.contextTokens);
 assert.deepEqual(restored.messages,canonical.messages);
});
